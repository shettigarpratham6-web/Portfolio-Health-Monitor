"""
Portfolio Health Monitor
Supervisor Agent
Orchestrates portfolio monitoring workflow, creates execution plans, delegates to specialized agents,
and handles task execution and failure recovery.
"""

from datetime import datetime, timezone
from enum import Enum
import logging
from typing import Any, Dict, List, Optional

from langsmith import traceable
from pydantic import BaseModel, Field

from app.agents.discovery_agent import CompanyTarget, DiscoveryAgent, DiscoveryAgentInput, DiscoveryOutput
from app.agents.impact_agent import ImpactAgent, ImpactAgentInput, PortfolioImpactReport
from app.agents.portfolio_agent import PortfolioAgent, PortfolioAgentInput, PortfolioContext
from app.agents.reporting_agent import MonitoringReport, ReportingAgent, ReportingAgentInput
from app.agents.verification_agent import VerificationAgent, VerificationAgentInput, VerificationOutput
from app.mcp.clients import MCPClient, get_mcp_client
from app.services.llm import LLMService, get_llm_service

logger = logging.getLogger("agentx.agents.supervisor")


# ------------------------------------------------------------------------------
# Input & Output Schemas
# ------------------------------------------------------------------------------
class MonitoringRequestType(str, Enum):
    """Types of monitoring workflows supported by Supervisor."""
    FULL_PORTFOLIO_CHECK = "full_portfolio_check"
    SINGLE_STOCK_DRILLDOWN = "single_stock_drilldown"
    SCHEDULED_MONITORING = "scheduled_monitoring"


class PhaseStatus(str, Enum):
    """Execution status for each workflow phase."""
    PENDING = "PENDING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    SKIPPED = "SKIPPED"
    FAILED = "FAILED"


class WorkflowPhase(BaseModel):
    """Execution state of a single monitoring phase."""
    phase_name: str
    assigned_agent: str
    status: PhaseStatus = PhaseStatus.PENDING
    details: Optional[str] = None
    started_at: Optional[str] = None
    completed_at: Optional[str] = None


class SupervisorExecutionPlan(BaseModel):
    """Execution plan generated by the Supervisor prior to task dispatch."""
    plan_id: str = Field(default_factory=lambda: f"plan-{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}")
    portfolio_id: str
    request_type: MonitoringRequestType
    target_tickers: List[str] = Field(default_factory=list)
    phases: List[WorkflowPhase] = Field(default_factory=list)
    planned_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class SupervisorInput(BaseModel):
    """Input payload to trigger the Supervisor Agent."""
    portfolio_id: str = Field(..., description="Target portfolio UUID")
    request_type: MonitoringRequestType = Field(
        default=MonitoringRequestType.FULL_PORTFOLIO_CHECK,
        description="Type of monitoring run to execute",
    )
    specific_tickers: Optional[List[str]] = Field(
        default=None,
        description="Optional filter for drill-downs on specific holdings",
    )
    max_news_per_target: int = Field(default=3, ge=1, le=10)
    max_filings_per_target: int = Field(default=2, ge=0, le=5)
    include_filings: bool = True
    include_news: bool = True
    persist_alerts: bool = True


class SupervisorOutput(BaseModel):
    """Final aggregated response produced by the Supervisor workflow."""
    status: str = Field(description="SUCCESS, PARTIAL_SUCCESS, or FAILED")
    portfolio_id: str
    execution_plan: SupervisorExecutionPlan
    portfolio_context: Optional[PortfolioContext] = None
    discovery_output: Optional[DiscoveryOutput] = None
    verification_output: Optional[VerificationOutput] = None
    impact_report: Optional[PortfolioImpactReport] = None
    monitoring_report: Optional[MonitoringReport] = None
    errors: List[str] = Field(default_factory=list)
    started_at: str
    completed_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    non_advisory_notice: str = (
        "Notice: This system provides objective risk and event monitoring only. "
        "It does NOT contain investment recommendations to buy, sell, or hold any financial security."
    )


# ------------------------------------------------------------------------------
# Supervisor Agent
# ------------------------------------------------------------------------------
class SupervisorAgent:
    """
    Supervisor Agent coordinates execution across all 5 specialized agents:
    1. Portfolio Intelligence Agent -> retrieves holdings & allocation metrics
    2. News & Filing Discovery Agent -> queries news & filings via Research MCP
    3. Research & Verification Agent -> corroborates facts, verifies claims & eliminates duplicates
    4. Portfolio Impact Agent -> determines deterministic holding impact & portfolio risk
    5. Alert & Reporting Agent -> stores events/alerts in DB & prepares structured report
    """

    def __init__(
        self,
        llm_service: Optional[LLMService] = None,
        mcp_client: Optional[MCPClient] = None,
        portfolio_agent: Optional[PortfolioAgent] = None,
        discovery_agent: Optional[DiscoveryAgent] = None,
        verification_agent: Optional[VerificationAgent] = None,
        impact_agent: Optional[ImpactAgent] = None,
        reporting_agent: Optional[ReportingAgent] = None,
    ) -> None:
        self.llm = llm_service or get_llm_service()
        self.mcp = mcp_client or get_mcp_client()

        # Sub-agents (can be injected or instantiated)
        self.portfolio_agent = portfolio_agent or PortfolioAgent(llm_service=self.llm, mcp_client=self.mcp)
        self.discovery_agent = discovery_agent or DiscoveryAgent(llm_service=self.llm, mcp_client=self.mcp)
        self.verification_agent = verification_agent or VerificationAgent(llm_service=self.llm, mcp_client=self.mcp)
        self.impact_agent = impact_agent or ImpactAgent(llm_service=self.llm, mcp_client=self.mcp)
        self.reporting_agent = reporting_agent or ReportingAgent(llm_service=self.llm, mcp_client=self.mcp)

    def create_execution_plan(self, req: SupervisorInput) -> SupervisorExecutionPlan:
        """Formulate a step-by-step execution plan based on the request type."""
        phases = [
            WorkflowPhase(phase_name="portfolio_intelligence", assigned_agent="PortfolioAgent"),
            WorkflowPhase(phase_name="news_and_filing_discovery", assigned_agent="DiscoveryAgent"),
            WorkflowPhase(phase_name="research_and_verification", assigned_agent="VerificationAgent"),
            WorkflowPhase(phase_name="portfolio_impact_analysis", assigned_agent="ImpactAgent"),
            WorkflowPhase(phase_name="alert_and_reporting", assigned_agent="ReportingAgent"),
        ]

        target_tickers = req.specific_tickers or []
        return SupervisorExecutionPlan(
            portfolio_id=req.portfolio_id,
            request_type=req.request_type,
            target_tickers=target_tickers,
            phases=phases,
        )

    @traceable(name="Supervisor Agent", run_type="chain")
    async def run(self, req: SupervisorInput) -> SupervisorOutput:
        """
        Execute the full multi-agent monitoring workflow with structured error recovery.
        """
        started_at = datetime.now(timezone.utc).isoformat()
        plan = self.create_execution_plan(req)
        errors: List[str] = []

        portfolio_context: Optional[PortfolioContext] = None
        discovery_output: Optional[DiscoveryOutput] = None
        verification_output: Optional[VerificationOutput] = None
        impact_report: Optional[PortfolioImpactReport] = None
        monitoring_report: Optional[MonitoringReport] = None

        logger.info(
            f"Supervisor starting run for portfolio '{req.portfolio_id}' [type={req.request_type.value}]"
        )

        # ----------------------------------------------------------------------
        # Phase 1: Portfolio Intelligence
        # ----------------------------------------------------------------------
        p1 = plan.phases[0]
        p1.status = PhaseStatus.RUNNING
        p1.started_at = datetime.now(timezone.utc).isoformat()
        try:
            logger.info("Phase 1: Retrieving portfolio context...")
            portfolio_context = await self.portfolio_agent.run(
                PortfolioAgentInput(portfolio_id=req.portfolio_id)
            )
            p1.status = PhaseStatus.COMPLETED
            p1.details = f"Loaded {len(portfolio_context.holdings)} holdings."
        except Exception as exc:
            err_msg = f"Phase 1 (Portfolio Intelligence) failed: {exc}"
            logger.error(err_msg, exc_info=True)
            p1.status = PhaseStatus.FAILED
            p1.details = str(exc)
            errors.append(err_msg)
            # Cannot proceed without portfolio context
            return self._finalize_output(
                status="FAILED",
                req=req,
                plan=plan,
                started_at=started_at,
                errors=errors,
            )
        finally:
            p1.completed_at = datetime.now(timezone.utc).isoformat()

        # Handle empty portfolio
        if not portfolio_context.holdings:
            logger.warning(f"Portfolio '{req.portfolio_id}' has no active holdings. Concluding early.")
            for remaining_phase in plan.phases[1:]:
                remaining_phase.status = PhaseStatus.SKIPPED
                remaining_phase.details = "No holdings found to monitor."

            empty_report = MonitoringReport(
                portfolio_id=req.portfolio_id,
                executive_summary="Portfolio contains no active holdings. No research or risk evaluation performed.",
                aggregate_risk_level="LOW",
                alerts=[],
            )
            return self._finalize_output(
                status="SUCCESS",
                req=req,
                plan=plan,
                started_at=started_at,
                errors=errors,
                portfolio_context=portfolio_context,
                monitoring_report=empty_report,
            )

        # Determine target companies for discovery
        targets: List[CompanyTarget] = []
        filter_tickers = {t.upper() for t in req.specific_tickers} if req.specific_tickers else None

        for h in portfolio_context.holdings:
            if filter_tickers and h.ticker.upper() not in filter_tickers:
                continue
            targets.append(
                CompanyTarget(
                    company_name=h.company_name,
                    ticker=h.ticker,
                    company_id=h.company_id,
                )
            )

        if not targets:
            err_msg = f"None of the requested tickers {req.specific_tickers} matched portfolio holdings."
            logger.warning(err_msg)
            for remaining_phase in plan.phases[1:]:
                remaining_phase.status = PhaseStatus.SKIPPED
                remaining_phase.details = err_msg
            errors.append(err_msg)
            return self._finalize_output(
                status="PARTIAL_SUCCESS",
                req=req,
                plan=plan,
                started_at=started_at,
                errors=errors,
                portfolio_context=portfolio_context,
            )

        # ----------------------------------------------------------------------
        # Phase 2: News & Filing Discovery
        # ----------------------------------------------------------------------
        p2 = plan.phases[1]
        p2.status = PhaseStatus.RUNNING
        p2.started_at = datetime.now(timezone.utc).isoformat()
        try:
            logger.info(f"Phase 2: Discovering news & filings for {len(targets)} targets...")
            discovery_output = await self.discovery_agent.run(
                DiscoveryAgentInput(
                    targets=targets,
                    max_news_per_target=req.max_news_per_target,
                    max_filings_per_target=req.max_filings_per_target,
                    include_filings=req.include_filings,
                    include_news=req.include_news,
                )
            )
            p2.status = PhaseStatus.COMPLETED
            p2.details = f"Discovered {discovery_output.total_discovered} events across {len(discovery_output.companies_searched)} companies."
        except Exception as exc:
            err_msg = f"Phase 2 (Discovery) failed: {exc}"
            logger.error(err_msg, exc_info=True)
            p2.status = PhaseStatus.FAILED
            p2.details = str(exc)
            errors.append(err_msg)
            # Continue with empty discovery so downstream still provides a report
            discovery_output = DiscoveryOutput(
                total_discovered=0,
                companies_searched=[t.ticker for t in targets],
                discovered_events=[],
                discovery_summary="Discovery failed; continuing with 0 events.",
            )
        finally:
            p2.completed_at = datetime.now(timezone.utc).isoformat()

        # ----------------------------------------------------------------------
        # Phase 3: Research & Verification
        # ----------------------------------------------------------------------
        p3 = plan.phases[2]
        p3.status = PhaseStatus.RUNNING
        p3.started_at = datetime.now(timezone.utc).isoformat()
        try:
            logger.info(f"Phase 3: Verifying {len(discovery_output.discovered_events)} discovered events...")
            verification_output = await self.verification_agent.run(
                VerificationAgentInput(
                    discovered_events=discovery_output.discovered_events,
                )
            )
            p3.status = PhaseStatus.COMPLETED
            p3.details = (
                f"Verified {verification_output.total_verified} events "
                f"({verification_output.duplicates_filtered} duplicates filtered)."
            )
        except Exception as exc:
            err_msg = f"Phase 3 (Verification) failed: {exc}"
            logger.error(err_msg, exc_info=True)
            p3.status = PhaseStatus.FAILED
            p3.details = str(exc)
            errors.append(err_msg)
            verification_output = VerificationOutput(
                total_reviewed=len(discovery_output.discovered_events),
                total_verified=0,
                duplicates_filtered=0,
                verified_events=[],
                verification_summary="Verification phase encountered an error.",
            )
        finally:
            p3.completed_at = datetime.now(timezone.utc).isoformat()

        # ----------------------------------------------------------------------
        # Phase 4: Portfolio Impact Analysis
        # ----------------------------------------------------------------------
        p4 = plan.phases[3]
        p4.status = PhaseStatus.RUNNING
        p4.started_at = datetime.now(timezone.utc).isoformat()
        try:
            logger.info("Phase 4: Running deterministic impact analysis...")
            impact_report = await self.impact_agent.run(
                ImpactAgentInput(
                    portfolio_context=portfolio_context,
                    verified_events=verification_output.verified_events,
                )
            )
            p4.status = PhaseStatus.COMPLETED
            p4.details = (
                f"Evaluated {impact_report.total_events_evaluated} events: "
                f"{impact_report.direct_impacts_count} direct impacts, "
                f"overall risk: {impact_report.aggregate_risk_level}."
            )
        except Exception as exc:
            err_msg = f"Phase 4 (Impact Analysis) failed: {exc}"
            logger.error(err_msg, exc_info=True)
            p4.status = PhaseStatus.FAILED
            p4.details = str(exc)
            errors.append(err_msg)
            impact_report = PortfolioImpactReport(
                portfolio_id=req.portfolio_id,
                portfolio_name=portfolio_context.name,
                total_events_evaluated=0,
                direct_impacts_count=0,
                indirect_impacts_count=0,
                aggregate_risk_level="LOW",
                holding_impacts=[],
                impact_summary="Impact analysis failed due to internal error.",
            )
        finally:
            p4.completed_at = datetime.now(timezone.utc).isoformat()

        # ----------------------------------------------------------------------
        # Phase 5: Alert & Reporting
        # ----------------------------------------------------------------------
        p5 = plan.phases[4]
        p5.status = PhaseStatus.RUNNING
        p5.started_at = datetime.now(timezone.utc).isoformat()
        try:
            logger.info("Phase 5: Generating final monitoring report and persisting alerts...")
            monitoring_report = await self.reporting_agent.run(
                ReportingAgentInput(
                    portfolio_id=req.portfolio_id,
                    impact_report=impact_report,
                    verified_events=verification_output.verified_events,
                    persist_to_database=req.persist_alerts,
                )
            )
            p5.status = PhaseStatus.COMPLETED
            p5.details = (
                f"Generated report with {len(monitoring_report.alerts)} alerts "
                f"({monitoring_report.persisted_alerts_count} persisted to DB)."
            )
        except Exception as exc:
            err_msg = f"Phase 5 (Reporting) failed: {exc}"
            logger.error(err_msg, exc_info=True)
            p5.status = PhaseStatus.FAILED
            p5.details = str(exc)
            errors.append(err_msg)
            monitoring_report = MonitoringReport(
                portfolio_id=req.portfolio_id,
                executive_summary="Monitoring completed, but report compilation/persistence failed.",
                aggregate_risk_level=impact_report.aggregate_risk_level if impact_report else "UNKNOWN",
                alerts=[],
            )
        finally:
            p5.completed_at = datetime.now(timezone.utc).isoformat()

        # Overall Status
        overall_status = "SUCCESS"
        if errors:
            overall_status = "PARTIAL_SUCCESS" if monitoring_report is not None else "FAILED"

        logger.info(f"Supervisor run finished for portfolio '{req.portfolio_id}' with status '{overall_status}'.")
        return self._finalize_output(
            status=overall_status,
            req=req,
            plan=plan,
            started_at=started_at,
            errors=errors,
            portfolio_context=portfolio_context,
            discovery_output=discovery_output,
            verification_output=verification_output,
            impact_report=impact_report,
            monitoring_report=monitoring_report,
        )

    def _finalize_output(
        self,
        status: str,
        req: SupervisorInput,
        plan: SupervisorExecutionPlan,
        started_at: str,
        errors: List[str],
        portfolio_context: Optional[PortfolioContext] = None,
        discovery_output: Optional[DiscoveryOutput] = None,
        verification_output: Optional[VerificationOutput] = None,
        impact_report: Optional[PortfolioImpactReport] = None,
        monitoring_report: Optional[MonitoringReport] = None,
    ) -> SupervisorOutput:
        return SupervisorOutput(
            status=status,
            portfolio_id=req.portfolio_id,
            execution_plan=plan,
            portfolio_context=portfolio_context,
            discovery_output=discovery_output,
            verification_output=verification_output,
            impact_report=impact_report,
            monitoring_report=monitoring_report,
            errors=errors,
            started_at=started_at,
        )
